export function snapshotFor(card: CatalogCard): PokemonCardSnapshot {
  return {
    source: 'CARDEX',
    externalId: card.id,
    setId: card.setId,
    setName: card.setName,
    number: card.number,
    rarity: card.rarity,
    supertype: card.supertype,
    subtypes: card.subtypes,
    types: card.types,
    imageSmall: card.imageSmall,
    imageLarge: card.imageLarge,
  };
}

export function findCard(cardId: string): CatalogCard | undefined {
  return CATALOG_CARDS.find((card) => card.id === cardId);
}
